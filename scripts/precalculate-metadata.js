/**
 * Build-time generator for the tour-match table, burial search rows, and map bounds.
 */
import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
import { buildBurialRecord } from "../src/features/locator/burialRecords.js";
import { FAB_TOUR_DEFINITIONS } from "../src/features/fab/tours.js";
import { buildTourRecord } from "../src/features/tours/tourRecords.js";
import { buildTourBurialMatches } from "../src/features/tours/tourRecordHarmonization.js";
import { getGeoJsonBounds, hasValidGeoJsonCoordinates } from "../src/shared/geoJsonBounds.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const GENERATED_BOUNDS_COMMENT = "// @generated by scripts/precalculate-metadata.js";

/**
 * Generate the build-time artifacts that keep runtime search and popup
 * enrichment cheap: the tour match table, the minified search payload, and the
 * static boundary constants.
 */
const cleanValue = (value) => {
  if (value === null || value === undefined) return '';
  return String(value).trim();
};

/**
 * The build pipeline needs the normalized burial record for both tour
 * matching and the compact search artifact. Build it once so `build:data`
 * spends time on the matching heuristic itself instead of recomputing the same
 * record shape in two full passes over ~97k burials.
 */
const buildNormalizedBurialEntries = (burialFeatures) => (
  burialFeatures.map((feature) => ({
    feature,
    properties: feature.properties || {},
    burialRecord: buildBurialRecord(feature),
  }))
);

const getRenderableTourFeatures = (definition, module) => {
  const features = module.default?.features || module.features || [];
  const validFeatures = features.filter((feature) => hasValidGeoJsonCoordinates(feature));

  if (validFeatures.length !== features.length) {
    console.warn(
      `Skipped ${features.length - validFeatures.length} invalid features while loading "${definition.name}" for build data.`
    );
  }

  return validFeatures;
};

async function precalculate() {
  console.log('Loading tour definitions...');
  const loadedRecords = [];
  for (const definition of FAB_TOUR_DEFINITIONS) {
    console.log(`Loading tour: ${definition.name}`);
    const module = await definition.load();
    const features = getRenderableTourFeatures(definition, module);
    const tourRecords = features.map((feature) => (
      buildTourRecord(feature, {
        tourKey: definition.key,
        tourName: definition.name,
      })
    ));
    loadedRecords.push(...tourRecords);
  }

  console.log(`Loaded ${loadedRecords.length} tour records.`);

  console.log('Loading burial source data...');
  const burialSourcePath = path.join(__dirname, "../src/data/Geo_Burials.json");
  const burialsData = JSON.parse(await fs.readFile(burialSourcePath, "utf8"));
  const burialFeatures = burialsData.features || [];
  console.log(`Loaded ${burialFeatures.length} burial features from GeoJSON (${burialSourcePath}).`);

  const normalizedBurialEntries = buildNormalizedBurialEntries(burialFeatures);

  console.log('Matching each tour stop to its best burial...');
  const matches = buildTourBurialMatches(
    loadedRecords,
    normalizedBurialEntries.map(({ burialRecord }) => burialRecord)
  );
  const matchCount = Object.keys(matches).length;

  console.log(`Done matching! Found ${matchCount} matches.`);

  const outputPath = path.join(__dirname, '../src/data/TourMatches.json');
  // Keep an auditable generated record of the exact burial-to-tour assignments.
  await fs.writeFile(outputPath, JSON.stringify(matches));
  console.log(`Wrote matches to ${outputPath}`);

  console.log('Generating minified search index...');
  const searchBurials = normalizedBurialEntries.map(({ feature, properties, burialRecord }) => {
    const match = matches[burialRecord.id];
    const sourceCoordinates = feature.geometry?.coordinates || null;

    // Keep keys short because this file ships to visitors. The worker prepares
    // its searchable strings once after download.
    const searchBurial = {
      i: properties.OBJECTID,
      f: cleanValue(properties.First_Name),
      l: cleanValue(properties.Last_Name),
      s: cleanValue(properties.Section),
      lo: cleanValue(properties.Lot),
      g: cleanValue(properties.Grave),
      t: cleanValue(properties.Tier),
      b: cleanValue(properties.Birth),
      d: cleanValue(properties.Death),
      tk: match ? match.tourKey : '',
      c: sourceCoordinates,
    };

    if (match) {
      searchBurial.tn = cleanValue(match.tourName);
      searchBurial.p = cleanValue(match.portraitImageName);
      searchBurial.u = cleanValue(match.biographyLink);
      searchBurial.x = cleanValue(match.extraTitle);
    }

    return searchBurial;
  });

  const searchOutputPath = path.join(__dirname, '../public/data/Search_Burials.json');
  const publicDataDir = path.join(__dirname, '../public/data');
  await fs.mkdir(publicDataDir, { recursive: true });
  // Keep this artifact as a top-level array; the locator worker reads it
  // directly and returns only the matching rows to React.
  await fs.writeFile(searchOutputPath, JSON.stringify(searchBurials));
  console.log(`Wrote minified search index to ${searchOutputPath}`);
  
  // Write static boundary helpers once so the client does not recompute them on
  // every page load.
  console.log('Loading BOUNDARY_POLYGON for static boundary calculations...');
  const boundaryModule = await import('../src/data/ARC_Boundary.json');
  const BOUNDARY_POLYGON = boundaryModule.default?.features?.[0] || boundaryModule.features?.[0];
  
  const [[south, west], [north, east]] = getGeoJsonBounds(BOUNDARY_POLYGON);
  const BOUNDARY_BBOX = [west, south, east, north];

  const constantsPath = path.join(__dirname, "../src/features/map/generatedBounds.js");
  const constantsContent = `${GENERATED_BOUNDS_COMMENT}
export const BOUNDARY_BBOX = ${JSON.stringify(BOUNDARY_BBOX)};
`;
  await fs.writeFile(constantsPath, constantsContent);
  console.log(`Wrote constants to ${constantsPath}`);
}

precalculate().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
